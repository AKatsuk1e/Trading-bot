@Composable
fun SignalsScreen(
    viewModel: TradingViewModel,
    modifier: Modifier = Modifier
) {
    val signals by viewModel.signals.collectAsStateWithLifecycle()
    val portfolio by viewModel.portfolio.collectAsStateWithLifecycle()
    var selectedFilter by remember { mutableStateOf("ALL") }

    val filteredSignals = when (selectedFilter) {
        "BUY" -> signals.filter { it.side == TradeSide.BUY }
        "SELL" -> signals.filter { it.side == TradeSide.SELL }
        "HIGH_EDGE" -> signals.filter { it.winProbability >= 0.58 }
        else -> signals
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(16.dp)
    ) {
        // Title & Filter Row
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Column {
                Text(
                    text = "Live & Profitable Signals",
                    fontSize = 18.sp,
                    fontWeight = FontWeight.Bold,
                    color = TextPrimary
                )
                Text(
                    text = "Generated by 4-agent consensus with 1/4 Kelly sizing",
                    fontSize = 11.sp,
                    color = TextMuted
                )
            }
        }

        Spacer(modifier = Modifier.height(12.dp))

        // Filter chips
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            val filters = listOf("ALL" to "All Signals", "BUY" to "Bullish", "SELL" to "Bearish", "HIGH_EDGE" to "High Edge (p≥58%)")
            filters.forEach { (key, label) ->
                val isSelected = selectedFilter == key
                Box(
                    modifier = Modifier
                        .clip(RoundedCornerShape(16.dp))
                        .background(if (isSelected) Color(0xFF00E5FF).copy(alpha = 0.15f) else DarkSurface)
                        .border(
                            width = 1.dp,
                            color = if (isSelected) Color(0xFF00E5FF) else DarkBorder,
                            shape = RoundedCornerShape(16.dp)
                        )
                        .clickable { selectedFilter = key }
                        .padding(horizontal = 12.dp, vertical = 6.dp)
                ) {
                    Text(
                        text = label,
                        fontSize = 11.sp,
                        fontWeight = FontWeight.SemiBold,
                        color = if (isSelected) Color(0xFF00E5FF) else TextSecondary
                    )
                }
            }
        }

        Spacer(modifier = Modifier.height(14.dp))

        if (filteredSignals.isEmpty()) {
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .weight(1f),
                contentAlignment = Alignment.Center
            ) {
                Column(horizontalAlignment = Alignment.CenterHorizontally) {
                    Icon(
                        imageVector = Icons.Default.Insights,
                        contentDescription = null,
                        tint = TextMuted,
                        modifier = Modifier.size(48.dp)
                    )
                    Spacer(modifier = Modifier.height(8.dp))
                    Text(
                        text = "Waiting for high-confidence agent consensus...",
                        color = TextSecondary,
                        fontSize = 13.sp
                    )
                    Text(
                        text = "Trigger analysis or turn on autonomous bot in Bot tab",
                        color = TextMuted,
                        fontSize = 11.sp
                    )
                }
            }
        } else {
            LazyColumn(
                modifier = Modifier.fillMaxWidth().weight(1f),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                items(filteredSignals, key = { it.id }) { signal ->
                    SignalCard(
                        signal = signal,
                        onExecute = {
                            val usd = portfolio.totalEquity * (signal.kellyPercentage / 100.0)
                            viewModel.executeManualTrade(signal.side, usd.coerceAtLeast(50.0))
                        }
                    )
                }
            }
        }
    }
}

@Composable
fun SignalCard(
    signal: TradingSignal,
    onExecute: () -> Unit,
    modifier: Modifier = Modifier
) {
    val isBuy = signal.side == TradeSide.BUY
    val sideColor = if (isBuy) NeonGreen else NeonRed

    Card(
        modifier = modifier.fillMaxWidth(),
        shape = RoundedCornerShape(14.dp),
        colors = CardDefaults.cardColors(containerColor = DarkSurface),
        border = androidx.compose.foundation.BorderStroke(1.dp, DarkBorder)
    ) {
        Column(modifier = Modifier.padding(14.dp)) {
            // Header
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Box(
                    modifier = Modifier
                        .background(sideColor.copy(alpha = 0.15f), RoundedCornerShape(8.dp))
                        .padding(horizontal = 8.dp, vertical = 4.dp)
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(
                            imageVector = if (isBuy) Icons.AutoMirrored.Filled.TrendingUp else Icons.AutoMirrored.Filled.TrendingDown,
                            contentDescription = null,
                            tint = sideColor,
                            modifier = Modifier.size(14.dp)
                        )
                        Spacer(modifier = Modifier.width(4.dp))
                        Text(
                            text = "${signal.side.name} ${signal.symbol}",
                            fontSize = 12.sp,
                            fontWeight = FontWeight.Bold,
                            color = sideColor
                        )
                    }
                }
                Spacer(modifier = Modifier.width(8.dp))
                Text(
                    text = "Timeframe: ${signal.timeframe}",
                    fontSize = 11.sp,
                    color = TextMuted
                )
                Spacer(modifier = Modifier.weight(1f))
                Text(
                    text = "Win Prob: ${(signal.winProbability * 100).toInt()}%",
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Bold,
                    color = KellyGold
                )
            }

            Spacer(modifier = Modifier.height(10.dp))

            // Pricing Row
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(DarkSurfaceVariant, RoundedCornerShape(8.dp))
                    .padding(10.dp),
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Column {
                    Text("ENTRY PRICE", fontSize = 9.sp, color = TextMuted)
                    Text("$${String.format("%.2f", signal.entryPrice)}", fontSize = 12.sp, fontWeight = FontWeight.Bold, color = TextPrimary)
                }
                Column {
                    Text("TARGET (TP +5%)", fontSize = 9.sp, color = TextMuted)
                    Text("$${String.format("%.2f", signal.targetPrice)}", fontSize = 12.sp, fontWeight = FontWeight.Bold, color = NeonGreen)
                }
                Column {
                    Text("STOP (SL -2%)", fontSize = 9.sp, color = TextMuted)
                    Text("$${String.format("%.2f", signal.stopLossPrice)}", fontSize = 12.sp, fontWeight = FontWeight.Bold, color = NeonRed)
                }
                Column {
                    Text("1/4 KELLY", fontSize = 9.sp, color = TextMuted)
                    Text("${String.format("%.2f", signal.kellyPercentage)}%", fontSize = 12.sp, fontWeight = FontWeight.Bold, color = KellyGold)
                }
            }

            Spacer(modifier = Modifier.height(8.dp))

            Text(
                text = signal.reasoning,
                fontSize = 11.sp,
                color = TextSecondary,
                lineHeight = 14.sp
            )

            Spacer(modifier = Modifier.height(10.dp))

            Button(
                onClick = onExecute,
                modifier = Modifier.fillMaxWidth().height(38.dp).testTag("execute_signal_${signal.id}"),
                colors = ButtonDefaults.buttonColors(containerColor = sideColor)
            ) {
                Icon(Icons.Default.Bolt, contentDescription = null, tint = if (isBuy) Color.Black else Color.White, modifier = Modifier.size(16.dp))
                Spacer(modifier = Modifier.width(6.dp))
                Text(
                    text = "EXECUTE ${signal.side.name} AT 1/4 KELLY",
                    fontSize = 11.sp,
                    fontWeight = FontWeight.Bold,
                    color = if (isBuy) Color.Black else Color.White
                )
            }
        }
    }
}
